--comment: the playdates the agent proposes. No uniqueness yet, on purpose: LAB 3 adds it.
--
-- Rows are never deleted. Cancelling sets status and cancelled_at, so the
-- table is also the record of what the agent did, for whom, and when.
-- The dog ids are plain columns with a foreign key, not a JPA relation: the
-- tools work with ids, and so does this table.
CREATE TABLE playdate (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_dog_id   BIGINT       NOT NULL REFERENCES dog (id),
    to_dog_id     BIGINT       NOT NULL REFERENCES dog (id),
    scheduled_on  DATE         NOT NULL,
    park          VARCHAR(40)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    created_by    VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    cancelled_at  TIMESTAMPTZ
);
--rollback DROP TABLE playdate;
